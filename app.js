/* TinoDash2 decision engine.
   Loads data/model.js (window.TINO_MODEL, generated by scripts/build_model.py)
   and provides the browser-side what-if controls. All computation stays on this
   device; nothing is transmitted. Display currency is rounded to the nearest $10
   (owner instruction). Educational decision support only - not advice. */
(() => {
  'use strict';

  const $ = (id) => document.getElementById(id);
  const M = window.TINO_MODEL || null;

  const fmt$ = (v) => {
    if (!Number.isFinite(v)) return '-';
    const r = Math.round(v / 10) * 10;
    return '$' + r.toLocaleString('en-US');
  };
  const pctFmt = (v, nd) => (Number.isFinite(v) ? (v * 100).toFixed(nd === undefined ? 2 : nd) + '%' : '-');
  const num = (id) => {
    const raw = $(id) ? $(id).value.trim() : '';
    return raw === '' ? null : Number(raw);
  };
  const clamp = (v, lo, hi) => Math.min(hi, Math.max(lo, v));

  /* ------------------------------------------------------------------ */
  /* Core math (mirrors scripts/build_model.py)                          */
  /* ------------------------------------------------------------------ */

  const A = M ? M.properties.A : null;
  const B = M ? M.properties.B : null;
  const AN = M ? M.anchors : {};

  function sccTax(assessed) {
    const rate = AN.scc_typical_tra_total || 0.011488;
    const fixed = AN.scc_fixed_charges_annual_base || 1010;
    return assessed * rate + fixed;
  }
  function sccTransferTax(value) {
    const per500 = AN.scc_transfer_tax_per_500 || 0.55;
    return Math.ceil(value / 500) * per500;
  }
  function fv(value, rate, years) {
    return value * Math.pow(1 + rate, years);
  }
  // Monthly simulation: parking yield on cash, stock growth on invested,
  // optional single crash applied to invested balances at crashYear.
  function simulate(invAmount, stockRate, treasuryRate, phaseMonths, crashYear, crashPct, horizonYears) {
    let cash = phaseMonths > 0 ? invAmount : 0;
    let invested = phaseMonths > 0 ? 0 : invAmount;
    const monthlyBuy = phaseMonths > 0 ? invAmount / phaseMonths : 0;
    const mRate = Math.pow(1 + stockRate, 1 / 12);
    const tRate = Math.pow(1 + treasuryRate, 1 / 12);
    const months = horizonYears * 12;
    for (let m = 1; m <= months; m += 1) {
      cash *= tRate;
      invested *= mRate;
      if (crashYear && m === crashYear * 12 && crashPct) invested *= (1 - crashPct);
      if (phaseMonths > 0 && m <= phaseMonths) {
        const buy = Math.min(monthlyBuy, cash);
        cash -= buy;
        invested += buy;
      }
    }
    return invested + cash;
  }

  function scenarioSet(state) {
    // low / base / high parameter rows for range outputs
    const S = M ? M.scenarios : {};
    const pick = (k) => S[k] || { low: 0, base: 0, high: 0 };
    return {
      app: pick('appreciation'),
      infl: pick('inflation'),
      stock: state.stock !== null ? { low: state.stock, base: state.stock, high: state.stock } : pick('stock_nominal'),
      treas: state.treasury !== null ? { low: state.treasury, base: state.treasury, high: state.treasury } : pick('treasury_parking'),
      comm: pick('commission_rate'),
      rentG: pick('rent_growth'),
    };
  }

  function pathOutputs(state) {
    const dy = state.transferYear - 2026;
    const H = state.horizon;
    const S = scenarioSet(state);
    const out = {};
    const cashBase = state.otherCash !== null ? state.otherCash : (M ? M.paths._params.liquid_cash_placeholder : 1500000);

    const values = ['low', 'base', 'high'].map((k) => ({
      k,
      aVal: fv(A.value_2026_base, S.app[k], dy),
      stock: S.stock[k],
      treas: S.treas[k],
      infl: S.infl[k],
      comm: S.comm[k],
    }));

    const allowance = AN.prop19_allowance_2025_2027 * Math.pow(1 + (M.scenarios.allowance_growth_per_year.base), dy);
    const esc121 = AN.sec121_exclusion_mfj || 500000;

    for (const v of values) {
      const netSale = v.aVal * (1 - v.comm) - sccTransferTax(v.aVal) - (state.closeCosts !== null ? state.closeCosts : 9000) - 160;
      const investable = netSale + cashBase;
      const assessedLive = Math.max(A.assessed_2026 * Math.pow(1.02, dy), v.aVal - allowance);
      const taxLive = sccTax(assessedLive);
      const taxRent = sccTax(v.aVal);
      const rentAnnual = state.rent !== null ? state.rent * 12 : A.market_rent_monthly[1] * 12 * Math.pow(1 + S.rentG.base, dy);
      const ins = (state.insurance !== null ? state.insurance : A.insurance_annual[1]) * Math.pow(1 + (M.scenarios.insurance_growth.base), dy);
      const util = (A.water_monthly[1] + A.electricity_net_monthly[1]) * 12;
      const maint = v.aVal * (A.maintenance_pct[1] + A.capital_reserve_pct);
      const carry = taxLive + ins + util + maint;
      const carryRent = taxRent + ins + util + maint;
      const imputed = rentAnnual;
      const mgmtVac = rentAnnual * ((B.management_pct[1] || 0.04) + (B.vacancy_pct[1] || 0.06));
      const noi = rentAnnual - mgmtVac - carryRent;

      const phased = simulate(investable, v.stock, v.treas, state.phaseMonths, state.crashYear, state.crashPct, H);
      const lump = simulate(investable, v.stock, v.treas, 0, state.crashYear, state.crashPct, H);
      const flowSum = (flow) => {
        let t = 0;
        for (let i = 0; i < H; i += 1) t += flow * Math.pow(1 + v.infl, i);
        return t;
      };
      // live N years then sell (sec 121 simplified, gain from stepped-up basis)
      const liveYears = clamp(state.liveYears !== null ? state.liveYears : 3, 0, H);
      const futureVal = v.aVal * Math.pow(1 + S.app.base, liveYears);
      const gain = futureVal * 0.95 - v.aVal;
      const taxable = Math.max(0, gain - esc121);
      const fedTax = taxable * 0.20 + taxable * (AN.niit_rate || 0.038);
      const caTax = taxable * 0.123 + (taxable > (AN.ftb_line62_threshold || 1e6) ? taxable * (AN.ftb_line62_1pct_over_1m || 0.01) : 0);
      const netLiveSell = futureVal * 0.95 - fedTax - caTax + cashBase * Math.pow(1 + v.stock, H);

      out[v.k] = {
        aVal: v.aVal,
        netSale, investable, taxLive, taxRent, rentAnnual, ins, util, maint,
        live: {
          annualNet: imputed - carry,
          terminal: v.aVal + cashBase * Math.pow(1 + v.stock, H) + flowSum(imputed - carry),
        },
        rent: {
          noi,
          terminal: v.aVal + cashBase * Math.pow(1 + v.stock, H) + flowSum(noi),
        },
        sellInvest: { terminal: lump },
        sellPhased: { terminal: phased, versusLump: phased - lump },
        liveThenSell: { terminal: netLiveSell, gain, fedTax, caTax, taxable },
      };
    }
    return out;
  }

  /* ------------------------------------------------------------------ */
  /* Rendering                                                           */
  /* ------------------------------------------------------------------ */

  function resultRows(res, state) {
    const tb = $('resultRows');
    if (!tb) return;
    const rows = [
      { key: 'sellPhased', label: 'Sell at transfer; phase into stocks over ' + state.phaseMonths + ' months (3M-2Y Treasuries first)' },
      { key: 'sellInvest', label: 'Sell at transfer; invest lump sum immediately' },
      { key: 'live', label: 'Live in inherited home (Prop 19 claimed, long-term occupancy)' },
      { key: 'rent', label: 'Rent inherited home (full reassessment; no exclusion)' },
      { key: 'liveThenSell', label: 'Mixed: live ' + state.liveYears + ' year(s), then sell (IRC 121 applied)' },
    ];
    tb.replaceChildren();
    for (const r of rows) {
      const tr = document.createElement('tr');
      const lo = res.low[r.key].terminal;
      const base = res.base[r.key].terminal;
      const hi = res.high[r.key].terminal;
      const cells = [
        '<td><strong>' + r.label + '</strong></td>',
        '<td class="num">' + fmt$(lo) + '</td>',
        '<td class="num">' + fmt$(base) + '</td>',
        '<td class="num">' + fmt$(hi) + '</td>',
        '<td class="num">' + fmt$(base / Math.pow(1 + (M.scenarios.inflation.base), state.horizon)) + '</td>',
        '<td><a href="taxes.html">Tax map</a> · <a href="black-swan.html">Stress tests</a></td>',
      ];
      tr.innerHTML = cells.join('');
      tb.appendChild(tr);
    }
  }

  function distributionChart(res) {
    const el = $('distribution');
    if (!el) return;
    const rows = [
      { key: 'sellPhased', label: 'Sell → phased (24-36 mo Treasuries → stocks)' },
      { key: 'sellInvest', label: 'Sell → immediate lump sum' },
      { key: 'live', label: 'Live in home (Prop 19)' },
      { key: 'rent', label: 'Rent home' },
      { key: 'liveThenSell', label: 'Mixed: live, then sell' },
    ];
    const vals = rows.map((r) => [res.low[r.key].terminal, res.base[r.key].terminal, res.high[r.key].terminal]);
    const max = Math.max.apply(null, vals.map((v) => v[2]));
    const min = Math.min.apply(null, vals.map((v) => v[0]));
    const span = Math.max(1, max - min);
    el.replaceChildren();
    rows.forEach((r, i) => {
      const [lo, mid, hi] = vals[i];
      const row = document.createElement('div');
      row.className = 'dist-row';
      const bar = document.createElement('div');
      bar.className = 'dist-bar';
      const left = ((lo - min) / span) * 100;
      const width = Math.max(0.8, ((hi - lo) / span) * 100);
      bar.style.left = left + '%';
      bar.style.width = width + '%';
      const dot = document.createElement('div');
      dot.className = 'dist-dot';
      dot.style.left = 'calc(' + ((mid - min) / span) * 100 + '% - 5px)';
      const label = document.createElement('div');
      label.className = 'dist-label';
      label.textContent = r.label;
      const track = document.createElement('div');
      track.className = 'dist-track';
      track.appendChild(bar);
      track.appendChild(dot);
      row.appendChild(label);
      row.appendChild(track);
      el.appendChild(row);
    });
    const cap = document.createElement('p');
    cap.className = 'muted small';
    cap.textContent = 'Bars = modelled low-to-high terminal value band (low/high growth scenarios); dot = base case. Ranges are scenario outputs, not probabilities.';
    el.appendChild(cap);
  }

  function tornado(res, state) {
    const el = $('tornado');
    if (!el) return;
    const base = res.base.sellPhased.terminal;
    const perturb = (make) => {
      const saved = Object.assign({}, state);
      const alt = make(saved);
      const r = pathOutputs(alt);
      return r.base.sellPhased.terminal - base;
    };
    const items = [];
    const deltas = [
      ['Stock return ±2 pts', (s) => Object.assign(s, { stock: clamp((s.stock === null ? 0.07 : s.stock) + 0.02, -0.5, 0.5) })],
      ['Home appreciation +2 pts', (s) => { const x = Object.assign({}, s); x.appBoost = 0.02; return x; }],
      ['Treasury parking yield −2 pts', (s) => Object.assign(s, { treasury: clamp((s.treasury === null ? 0.045 : s.treasury) - 0.02, 0, 0.2) })],
      ['Phase window +12 months', (s) => Object.assign(s, { phaseMonths: clamp(s.phaseMonths + 12, 6, 60) })],
    ];
    for (const [label, make] of deltas) {
      // appreciation boost handled via appBoost through a wrapper
      let d;
      if (label.startsWith('Home')) {
        const savedApp = M.scenarios.appreciation.base;
        const origFv = window.__fv;
        window.__fv = fv;
        const dy = state.transferYear - 2026;
        const boosted = (1 + savedApp + 0.02) ** dy / (1 + savedApp) ** dy;
        d = (res.base.sellPhased.terminal * boosted) - base;
      } else {
        d = perturb(make);
      }
      items.push({ label, d });
    }
    const maxAbs = Math.max.apply(null, items.map((i) => Math.abs(i.d))) || 1;
    el.replaceChildren();
    for (const it of items) {
      const row = document.createElement('div');
      row.className = 'tornado-row';
      const width = (Math.abs(it.d) / maxAbs) * 50;
      const dir = it.d >= 0 ? 'pos' : 'neg';
      row.innerHTML = '<div>' + it.label + '</div>' +
        '<div class="tornado-track"><div class="tornado-bar ' + dir + '" style="width:' + width + '%"></div></div>' +
        '<div class="tornado-val">' + (it.d >= 0 ? '+' : '') + fmt$(it.d) + '</div>';
      el.appendChild(row);
    }
  }

  function yearTable(res, state) {
    const body = $('annualProjectionRows');
    if (!body) return;
    body.replaceChildren();
    const dy0 = state.transferYear - 2026;
    const app = M.scenarios.appreciation.base;
    const infl = M.scenarios.inflation.base;
    const S = scenarioSet(state);
    const allowance = AN.prop19_allowance_2025_2027 * Math.pow(1 + M.scenarios.allowance_growth_per_year.base, dy0);
    const rows = Math.min(state.horizon, 30);
    for (let y = 0; y <= rows; y += 1) {
      const val = fv(A.value_2026_base, app, dy0 + y);
      const assessedLive = Math.max(A.assessed_2026 * Math.pow(1.02, dy0 + y), val - allowance);
      const assessedRent = val;
      const taxLive = sccTax(assessedLive);
      const taxRent = sccTax(assessedRent);
      const rent = (state.rent !== null ? state.rent : A.market_rent_monthly[1]) * Math.pow(1 + S.rentG.base, dy0 + y);
      const tr = document.createElement('tr');
      tr.innerHTML =
        '<td>' + (state.transferYear + y) + '</td>' +
        '<td class="num">' + fmt$(val) + '</td>' +
        '<td class="num">' + fmt$(assessedLive) + '</td>' +
        '<td class="num">' + fmt$(taxLive) + '</td>' +
        '<td class="num">' + fmt$(assessedRent) + '</td>' +
        '<td class="num">' + fmt$(taxRent) + '</td>' +
        '<td class="num">' + fmt$(rent) + '</td>' +
        '<td><a href="sources.html#src-boe-prop19">Prop 19 rule</a> · <a href="sources.html#src-scc-rate">TRA rate</a></td>';
      body.appendChild(tr);
    }
  }

  /* ------------------------------------------------------------------ */
  /* Projections page wiring                                             */
  /* ------------------------------------------------------------------ */

  function readState() {
    const state = {
      transferYear: num('transferYear') || 2045,
      horizon: num('horizon') || 30,
      stock: num('stockReturn') === null ? null : num('stockReturn') / 100,
      treasury: num('treasuryYield') === null ? null : num('treasuryYield') / 100,
      phaseMonths: num('phaseMonths') || 30,
      crashYear: num('crashYear'),
      crashPct: num('drawdown') === null ? null : num('drawdown') / 100,
      rent: num('marketRent'),
      insurance: num('insurance'),
      otherCash: num('otherCash'),
      closeCosts: num('closeCosts'),
      liveYears: num('liveYears'),
    };
    if (state.crashYear !== null && state.crashPct === null) state.crashPct = 0.5;
    if (state.crashPct !== null && state.crashYear === null) state.crashYear = 1;
    return state;
  }

  function validate(state) {
    const errors = [];
    if (state.horizon < 1 || state.horizon > 50) errors.push('Horizon must be 1-50 years.');
    if (![2040, 2045, 2050].includes(state.transferYear) && !(state.transferYear >= 2026 && state.transferYear <= 2060)) errors.push('Transfer year must be between 2026 and 2060.');
    if (state.phaseMonths < 1 || state.phaseMonths > 60) errors.push('Phase window must be 1-60 months (policy default 24-36).');
    if (state.crashPct !== null && (state.crashPct < 0 || state.crashPct > 1)) errors.push('Drawdown must be 0-100%.');
    if (state.stock !== null && (state.stock <= -0.99 || state.stock > 0.5)) errors.push('Stock return must be between -99% and +50%.');
    return errors;
  }

  function runProjections() {
    const status = $('modelStatus');
    const state = readState();
    const errors = validate(state);
    if (errors.length) {
      if (status) status.textContent = errors.join(' ');
      return;
    }
    const res = pathOutputs(state);
    resultRows(res, state);
    distributionChart(res);
    tornado(res, state);
    yearTable(res, state);
    const panel = $('modelResults');
    if (panel) panel.hidden = false;
    const rec = $('recOutput');
    if (rec && M) {
      const order = [
        ['sellPhased', 'Sell → phased reinvestment'],
        ['sellInvest', 'Sell → immediate lump sum'],
        ['live', 'Live in home (Prop 19)'],
        ['rent', 'Rent home'],
        ['liveThenSell', 'Live, then sell'],
      ].map(([k, label]) => ({ k, label, v: res.base[k].terminal }))
        .sort((a, b) => b.v - a.v);
      const lead = order[0];
      rec.innerHTML = '<p><strong>Engine ranking at these inputs (base case, nominal):</strong></p>' +
        '<ol>' + order.map((o) => '<li>' + o.label + ' — ' + fmt$(o.v) + '</li>').join('') + '</ol>' +
        '<p class="muted small">If the ranking moved after your change, record it in the decision log. Ranking is pre-tax for flows; sale taxes modeled for live-then-sell only. Verify with a CPA before acting.</p>';
    }
    if (status) status.textContent = 'Recalculated locally at ' + new Date().toLocaleTimeString() + '. Nothing was saved or transmitted.';
  }

  function wireProjections() {
    const form = $('scenarioForm');
    if (!form) return;
    form.addEventListener('submit', (e) => { e.preventDefault(); runProjections(); });
    form.addEventListener('reset', () => {
      const status = $('modelStatus');
      if (status) status.textContent = 'Inputs cleared. Defaults return on the next run.';
    });
    const printBtn = $('printBrief');
    if (printBtn) printBtn.addEventListener('click', () => window.print());
    // Prefill defaults from the model
    const P = M.paths._params;
    $('transferYear').value = '2045';
    $('horizon').value = '30';
    $('phaseMonths').value = '30';
    $('treasuryYield').value = String(AN.treasury_2yr || 4.61);
    const note = $('defaultNote');
    if (note) {
      note.textContent = 'Defaults: transfer 2045, 30-year horizon, ' + fmt$(P.investable.base) + ' investable (net sale ' + fmt$(P.net_sale_proceeds.base) + ' + planning cash ' + fmt$(P.liquid_cash_placeholder) + '), Treasuries ' + pctFmt((AN.treasury_2yr || 4.61) / 100) + ' (official Nov 25, 2026 curve).';
    }
  }

  /* ------------------------------------------------------------------ */
  /* Black swan page wiring                                              */
  /* ------------------------------------------------------------------ */

  function runBlackSwan() {
    const table = $('crashTable');
    if (!table) return;
    const inv = num('bsAmount') || (M ? M.black_swan.phased_tests.parking_amount_planning : 7141300);
    const stock = (num('bsStock') === null ? 7.0 : num('bsStock')) / 100;
    const treas = (num('bsTreasury') === null ? 4.5 : num('bsTreasury')) / 100;
    const horizon = num('bsHorizon') || 30;
    const crashes = [
      [1, 0.50, '2008-style, first year'],
      [2, 0.50, '2008-style, second year'],
      [3, 0.40, '2008-style, third year'],
      [1, 0.89, '1929-style, first year'],
      [null, 0, 'No crash (opportunity cost test)'],
    ];
    const uY = num('bsCrashYear');
    const uD = num('bsDrawdown') === null ? null : num('bsDrawdown') / 100;
    if (uY !== null && uD !== null) crashes.push([uY, uD, 'Your custom scenario']);
    table.replaceChildren();
    for (const [year, cp, label] of crashes) {
      const tr = document.createElement('tr');
      const cells = [];
      let worst = null;
      for (const phase of [0, 24, 30, 36]) {
        const v = simulate(inv, stock, treas, phase, year, cp, horizon);
        cells.push(v);
        if (worst === null || v > worst) worst = v;
      }
      const best = Math.max.apply(null, cells.slice(1));
      const tr2 = tr;
      tr2.innerHTML =
        '<td><strong>' + label + '</strong></td>' +
        '<td class="num">' + fmt$(cells[0]) + '</td>' +
        '<td class="num">' + fmt$(cells[1]) + '</td>' +
        '<td class="num">' + fmt$(cells[2]) + '</td>' +
        '<td class="num">' + fmt$(cells[3]) + '</td>' +
        '<td class="num ' + (best > cells[0] ? 'good' : 'bad') + '">' + fmt$(best - cells[0]) + '</td>' +
        '<td><a href="sources.html#src-treasury">Treasury yields</a> · <a href="sources.html#src-fred">Index anchors</a></td>';
      table.appendChild(tr);
    }
    const note = $('bsNote');
    if (note) {
      note.textContent = 'Inputs: ' + fmt$(inv) + ' parked then phased; stocks ' + pctFmt(stock) + '; parking ' + pctFmt(treas) + '; horizon ' + horizon + ' years. Crash applied to invested balances only in the selected year; Treasuries unaffected (yields assumed constant - real crises reset them; see reinvestment-risk note).';
    }
  }

  function wireBlackSwan() {
    const form = $('bsForm');
    if (!form) return;
    form.addEventListener('submit', (e) => { e.preventDefault(); runBlackSwan(); });
    runBlackSwan();
  }

  /* ------------------------------------------------------------------ */

  function init() {
    const page = document.body.getAttribute('data-page') || '';
    if (page === 'projections') wireProjections();
    if (page === 'black-swan') wireBlackSwan();
    const pb = $('printBrief');
    if (pb && page === 'briefing') pb.addEventListener('click', () => window.print());
    if (!M) {
      const st = $('modelStatus');
      if (st) st.textContent = 'Model data (data/model.js) not loaded - run scripts/build_model.py.';
    }
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})();
